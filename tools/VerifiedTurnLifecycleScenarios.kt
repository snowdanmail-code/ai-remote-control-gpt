package com.example.airemote

fun main() {
    var count = 0
    fun yes(value: Boolean, why: String) { check(value) { why }; count++ }
    fun frame(n: Long, time: Long, state: TurnDisplayState = TurnDisplayState.READY,
              stable: Boolean = true, table: String = "table-confirmed", hand: String = "hand-confirmed",
              epoch: Long = 7, window: Long = 3, verified: Boolean = true,
              stop: Boolean = false, consistent: Boolean = true, now: Long = time) = TurnCycleFrame(
        table, hand, verified, true, epoch, window, n, time, now, stop, state, stable, consistent)
    val t = VerifiedTurnLifecycle()
    fun push(f: TurnCycleFrame): TurnCycleReport = t.observe(f)
    yes(push(frame(1, 1000)).phase == TurnCyclePhase.OPENING, "one frame is not a turn")
    yes(push(frame(2, 1200)).phase == TurnCyclePhase.VISIBLE_DIAGNOSTIC, "two distinct ready frames")
    yes(t.snapshot(1200).visibleOrdinal == 1L, "first diagnostic ordinal")
    yes(!t.snapshot(1200).authorizesTap, "never enables touch")
    yes(!t.snapshot(1200).independentlyVerifiesTurn, "not independent proof")
    yes(push(frame(3, 1400)).visibleOrdinal == 1L, "persistent buttons are same turn")
    yes(push(frame(4, 1600, TurnDisplayState.PREACTION)).phase == TurnCyclePhase.CLOSING, "one missing frame")
    yes(push(frame(5, 1800)).phase == TurnCyclePhase.VISIBLE_DIAGNOSTIC, "flicker keeps same turn")
    yes(push(frame(6, 2000, TurnDisplayState.WAITING)).phase == TurnCyclePhase.CLOSING, "closing begins")
    yes(push(frame(7, 2200, TurnDisplayState.WAITING)).phase == TurnCyclePhase.CLOSED, "two nonactive close")
    yes(push(frame(8, 2400)).phase == TurnCyclePhase.OPENING, "next turn starts")
    yes(push(frame(9, 2600)).visibleOrdinal == 2L, "next distinct turn")
    yes(push(frame(9, 2800)).phase == TurnCyclePhase.SUSPENDED, "duplicate quarantined")
    yes(push(frame(10, 3000)).phase == TurnCyclePhase.SUSPENDED, "cannot reopen after ambiguity")
    yes(push(frame(11, 3200, TurnDisplayState.WAITING)).phase == TurnCyclePhase.SUSPENDED, "one inactive not enough")
    yes(push(frame(12, 3400, TurnDisplayState.WAITING)).phase == TurnCyclePhase.CLOSED, "recover after two inactive")
    yes(push(frame(13, 3600)).phase == TurnCyclePhase.OPENING, "recover with revalidation")
    yes(push(frame(14, 3800)).visibleOrdinal == 3L, "third diagnostic turn")
    yes(push(frame(15, 4000, hand = "new-hand")).phase == TurnCyclePhase.OPENING, "new hand resets")
    yes(push(frame(16, 4200, hand = "new-hand")).visibleOrdinal == 1L, "new hand first ordinal")
    yes(push(frame(17, 4400, window = 4)).phase == TurnCyclePhase.OPENING, "new window resets")
    yes(push(frame(18, 4600, window = 4)).visibleOrdinal == 1L, "new window reconfirmed")
    yes(push(frame(19, 4800, epoch = 8)).phase == TurnCyclePhase.OPENING, "epoch reset")
    yes(push(frame(20, 5000, epoch = 8)).phase == TurnCyclePhase.VISIBLE_DIAGNOSTIC, "epoch reconfirmed")
    yes(push(frame(21, 5200, epoch = 8, stop = true)).phase == TurnCyclePhase.UNKNOWN, "STOP clears")
    yes(t.snapshot(5200).visibleOrdinal == 0L, "STOP clears ordinal")
    yes(push(frame(1, 5400, verified = false)).phase == TurnCyclePhase.SUSPENDED, "no identity")
    yes(push(frame(2, 5600)).phase == TurnCyclePhase.SUSPENDED, "no ready on fault recovery")
    yes(push(frame(3, 5800, TurnDisplayState.WAITING)).phase == TurnCyclePhase.SUSPENDED, "recovery first inactive")
    yes(push(frame(4, 6000, TurnDisplayState.WAITING)).phase == TurnCyclePhase.CLOSED, "recovery second inactive")
    yes(push(frame(5, 6200)).phase == TurnCyclePhase.OPENING, "reopen first")
    yes(push(frame(6, 6400)).phase == TurnCyclePhase.VISIBLE_DIAGNOSTIC, "reopen second")
    yes(push(frame(7, 6600, stable = false)).phase == TurnCyclePhase.SUSPENDED, "unstable labels")
    yes(push(frame(8, 6800, TurnDisplayState.WAITING)).phase == TurnCyclePhase.SUSPENDED, "must requalify")
    yes(push(frame(9, 7000, TurnDisplayState.WAITING)).phase == TurnCyclePhase.CLOSED, "clears after wait")
    yes(push(frame(10, 7200, consistent = false)).phase == TurnCyclePhase.SUSPENDED, "contradictory labels")
    yes(push(frame(11, 7400, TurnDisplayState.BET_SIZING)).phase == TurnCyclePhase.SUSPENDED, "bet mode blocks")
    yes(push(frame(12, 7600, TurnDisplayState.WAITING)).phase == TurnCyclePhase.SUSPENDED, "still blocked")
    yes(push(frame(13, 7800, TurnDisplayState.WAITING)).phase == TurnCyclePhase.CLOSED, "recover")
    yes(push(frame(14, 8000)).phase == TurnCyclePhase.OPENING, "open before gap")
    yes(push(frame(15, 12000)).phase == TurnCyclePhase.SUSPENDED, "gap blocks")
    yes(push(frame(16, 12200)).phase == TurnCyclePhase.SUSPENDED, "gap requires close")
    yes(push(frame(17, 12400, TurnDisplayState.WAITING)).phase == TurnCyclePhase.SUSPENDED, "close first")
    yes(push(frame(18, 12600, TurnDisplayState.WAITING)).phase == TurnCyclePhase.CLOSED, "close second")
    yes(push(frame(19, 12800)).phase == TurnCyclePhase.OPENING, "new opening")
    yes(push(frame(20, 13000, now = 15001)).phase == TurnCyclePhase.SUSPENDED, "old frame blocked")
    yes(t.snapshot(16000).phase == TurnCyclePhase.SUSPENDED, "old state cannot be reused")
    t.reset()
    yes(t.snapshot(1).phase == TurnCyclePhase.UNKNOWN, "reset")
    println("PASS: $count turn lifecycle JVM assertions")
}
